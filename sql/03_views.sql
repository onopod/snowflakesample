CREATE OR REPLACE VIEW CF_DEMO.MART.PUBLIC_PROJECTS AS
SELECT PROJECT_ID, PROJECT_NAME, LOCATION, LOAN_PRINCIPAL, ANNUAL_INTEREST_RATE
FROM CF_DEMO.RAW.PROJECTS;
CREATE OR REPLACE VIEW CF_DEMO.MART.PUBLIC_CASH_EVENTS AS
SELECT EVENT_ID, PROJECT_ID, COUNTERPARTY, CATEGORY, PLANNED_DATE, PLANNED_AMOUNT, ACTUAL_DATE, ACTUAL_AMOUNT
FROM CF_DEMO.RAW.CASH_EVENTS;
-- Separate aggregates: do NOT union/sum planned and actual as though both are paid.
CREATE OR REPLACE VIEW CF_DEMO.MART.ACTUAL_MONTHLY AS
SELECT PROJECT_ID, DATE_TRUNC('MONTH',ACTUAL_DATE)::DATE AS MONTH, SUM(ACTUAL_AMOUNT) AS NET_CASH
FROM CF_DEMO.RAW.CASH_EVENTS WHERE ACTUAL_DATE IS NOT NULL GROUP BY 1,2;
CREATE OR REPLACE VIEW CF_DEMO.MART.UNSETTLED_PLAN_MONTHLY AS
SELECT PROJECT_ID, DATE_TRUNC('MONTH',PLANNED_DATE)::DATE AS MONTH, SUM(PLANNED_AMOUNT) AS NET_CASH
FROM CF_DEMO.RAW.CASH_EVENTS WHERE ACTUAL_DATE IS NULL GROUP BY 1,2;
