CREATE DATABASE IF NOT EXISTS CF_DEMO;
CREATE SCHEMA IF NOT EXISTS CF_DEMO.RAW;
CREATE SCHEMA IF NOT EXISTS CF_DEMO.MART;
CREATE TABLE IF NOT EXISTS CF_DEMO.RAW.PROJECTS (
 PROJECT_ID VARCHAR NOT NULL, PROJECT_NAME VARCHAR NOT NULL, LOCATION VARCHAR,
 LOAN_PRINCIPAL NUMBER(18,0), ANNUAL_INTEREST_RATE NUMBER(8,6)
);
CREATE TABLE IF NOT EXISTS CF_DEMO.RAW.CASH_EVENTS (
 EVENT_ID VARCHAR NOT NULL, PROJECT_ID VARCHAR NOT NULL, COUNTERPARTY VARCHAR,
 CATEGORY VARCHAR NOT NULL, PLANNED_DATE DATE NOT NULL, PLANNED_AMOUNT NUMBER(18,0) NOT NULL,
 ACTUAL_DATE DATE, ACTUAL_AMOUNT NUMBER(18,0)
);
-- Snowflake standard table uniqueness constraints are not enforced.
-- Seed MERGE and application validation enforce demo event identity.
